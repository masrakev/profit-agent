"""Citations attached in code: the golden questions before and after (Task 5 B4, ADR 0022).

    uv run python -m bench.citation_attach     # writes bench/reports/citation-attach.md

Inputs: three golden runs with economy routing at the commit before the change (`dc50ce6`)
and three at a commit with it (`f1c146b`), live, in bench/reports/citation-attach/before/ and
after/. Per run: the pass rate, regenerations (in all, and the answers that needed one), the
citations code attached, verifier violations, cost, and the failed checks by kind.
"""

import argparse
import json
import statistics
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from bench.runner.report import REPORT_DIR

RUNS = REPORT_DIR / "citation-attach"
COMMITS = {"before": "dc50ce6", "after": "f1c146b"}


@dataclass(frozen=True)
class RunStats:
    run: str
    passed: int
    active: int
    answered: int
    regenerations: int
    regenerated_answers: int
    attached: int
    attached_answers: int
    violations: int
    cost_usd: float
    failed: dict[str, int]

    @property
    def pass_rate(self) -> float:
        return self.passed / self.active


def run_stats(path: Path) -> RunStats:
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    questions = [q for q in data["questions"] if not q.get("pending")]
    regenerations = [int(q.get("regenerations") or 0) for q in questions]
    attached = [int(q.get("citations_attached") or 0) for q in questions]
    failed = Counter(
        check.split(":", 1)[0].split(" ", 1)[0]
        for q in questions
        for check in q.get("failed_checks") or []
    )
    s = data["summary"]
    return RunStats(
        run=path.stem,
        passed=int(s["passed"]),
        active=int(s["active"]),
        answered=sum(q.get("status") == "answered" for q in questions),
        regenerations=sum(regenerations),
        regenerated_answers=sum(r > 0 for r in regenerations),
        attached=sum(attached),
        attached_answers=sum(a > 0 for a in attached),
        violations=int(s["verifier_violations_in_answers"]),
        cost_usd=float(s["cost_usd"]),
        failed=dict(sorted(failed.items())),
    )


def load(folder: Path) -> dict[str, list[RunStats]]:
    return {
        label: [run_stats(p) for p in sorted((folder / label).glob("golden-*.json"))]
        for label in COMMITS
    }


def _spread(values: list[float], fmt: str, unit: str = "") -> str:
    def f(x: float) -> str:
        return format(x, fmt) + unit

    return f"{f(statistics.mean(values))} ({f(min(values))} to {f(max(values))})"


def report(runs: dict[str, list[RunStats]]) -> str:
    before, after = runs["before"], runs["after"]
    lines = [
        "# Citations attached in code: before and after",
        "",
        "Generated by `uv run python -m bench.citation_attach`. Golden questions, economy routing, "
        f"live model: three runs at `{COMMITS['before']}` (before) and three at "
        f"`{COMMITS['after']}` (after attaching the fact of a named metric in code, ADR 0022). "
        "Runs are in `bench/reports/citation-attach/`.",
        "",
        "| Run | Commit | Passed | Pass rate | Regenerations | Answers regenerated | "
        "Citations attached | Answers with one attached | Verifier violations | Cost USD |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for label, group in runs.items():
        for r in group:
            lines.append(
                f"| `{r.run}` | {COMMITS[label]} | {r.passed} / {r.active} | {r.pass_rate:.0%} | "
                f"{r.regenerations} | {r.regenerated_answers} / {r.answered} | {r.attached} | "
                f"{r.attached_answers} | {r.violations} | {r.cost_usd:.4f} |"
            )
    lines += [
        "",
        "Mean (min to max) over the three runs:",
        "",
        "| | Pass rate | Regenerations | Answers regenerated | Citations attached |",
        "| --- | --- | --- | --- | --- |",
    ]
    for label, group in runs.items():
        lines.append(
            f"| {label} | {_spread([r.pass_rate * 100 for r in group], '.1f', '%')} | "
            f"{_spread([float(r.regenerations) for r in group], '.1f')} | "
            f"{_spread([float(r.regenerated_answers) for r in group], '.1f')} | "
            f"{_spread([float(r.attached) for r in group], '.1f')} |"
        )
    kinds = sorted({k for group in runs.values() for r in group for k in r.failed})
    lines += [
        "",
        "Failed checks by kind, summed over the three runs (`reference`: the answer does not "
        "cite the fact the question is about; `mention`: it does not name the expected entity; "
        "`root_cause`: the wrong top cause):",
        "",
        "| | " + " | ".join(kinds) + " |",
        "| --- |" + " --- |" * len(kinds),
    ]
    for label, group in runs.items():
        counts = [str(sum(r.failed.get(k, 0) for r in group)) for k in kinds]
        lines.append(f"| {label} | " + " | ".join(counts) + " |")
    rate = [statistics.mean(r.pass_rate for r in g) * 100 for g in (before, after)]
    failures = sum(sum(r.failed.values()) for r in after)
    references = sum(r.failed.get("reference", 0) for r in after)
    regen = [statistics.mean(r.regenerations for r in g) for g in (before, after)]
    lines += [
        "",
        f"Reading: code attached {sum(r.attached for r in after)} citations in "
        f"{sum(r.attached_answers for r in after)} answers over the three runs after, none "
        f"before. The pass rate moved from {rate[0]:.1f}% to {rate[1]:.1f}% and regenerations "
        f"from {regen[0]:.1f} to {regen[1]:.1f} a run: both within the spread of three runs, "
        f"so no change is shown at this size. Of the {failures} failed checks after, "
        f"{references} are `reference` checks: the answer does not cite the fact of the "
        "metric the question asks about. Code attaches a fact only when a sentence names its "
        "metric and exactly one fact seen in the session fits, so these stay misses.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Golden questions before and after B4")
    parser.add_argument("--runs", type=Path, default=RUNS)
    parser.add_argument("--out", type=Path, default=REPORT_DIR)
    args = parser.parse_args(argv)
    text = report(load(args.runs))
    (args.out / "citation-attach.md").write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
